/** the units time is told in, and the seconds in each: from nanoseconds, so the first taps count */
const UNITS = [
  ["nanosecond", 1e-9],
  ["microsecond", 1e-6],
  ["millisecond", 1e-3],
  ["second", 1],
  ["minute", 60],
  ["hour", 3600],
  ["day", 86_400],
  ["week", 604_800],
  ["month", 2_628_000],
  ["year", 31_536_000],
] as const;
/** seconds of service time told in the largest unit they fill, with three digits (cut, never rounded up, so a rolling count
 * never shows more than there is): 375 ns, 1.50 µs, 12.0 ms, 45.2 secs, 3.00 hrs, 12.3K yrs */
export const fmt = (s: number): string => parts(s).join("");
/** seconds told as fmt() does, split into the number and the unit with its space before it (the compact "K", "Mio." go with
 * the unit): so the score can keep both in slots of their own */
export const parts = (s: number): [string, string] => {
  const [unit, size] = UNITS.findLast(([, n]) => s >= n) ?? UNITS[0];
  const n = s / size;
  const f = (x: number) =>
    new Intl.NumberFormat(LOCALE, {
      style: "unit",
      unit,
      unitDisplay: "short",
      notation: x >= 1e4 ? "compact" : "standard",
      minimumSignificantDigits: x ? 3 : 1,
      maximumSignificantDigits: 3,
      roundingMode: "trunc",
    }).formatToParts(x);
  const out = f(n);
  // German and Italian have no short word for thousands: 12’300 would not fit the number's slot, so it is 12.3 with a k
  if (n >= 1e4 && !out.some((p) => p.type === "compact")) {
    const [a, b] = split(f(n / 1000));
    return [a, `k${b}`];
  }
  return split(out);
};
const split = (out: Intl.NumberFormatPart[]): [string, string] => {
  const num = out.findLastIndex((p) => NUM.has(p.type)) + 1;
  return [out.slice(0, num), out.slice(num)].map((ps) => ps.map((p) => p.value).join("")) as [string, string];
};
const NUM = new Set(["integer", "decimal", "fraction", "group", "minusSign"]);
